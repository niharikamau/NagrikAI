const asyncHandler = require("express-async-handler");
const Complaint = require("../models/Complaint");
const Sensor = require("../models/Sensor");
const { getNextSequence } = require("../utils/counter");
// @route   GET /api/sensors
// @access  Private (admin)
const getSensors = asyncHandler(async (req, res) => {
  const sensors = await Sensor.find({}).sort({ id: 1 });

  const now = Date.now();
  const OFFLINE_TIMEOUT = 3000; // 3 seconds

  const updatedSensors = sensors.map(sensor => {
    const sensorData = sensor.toObject();

    if (
      !sensorData.lastReadingAt ||
      now - new Date(sensorData.lastReadingAt).getTime() > OFFLINE_TIMEOUT
    ) {
      sensorData.status = "Offline";
    } else {
      sensorData.status = "Online";
    }

    return sensorData;
  });

  res.status(200).json({
    success: true,
    sensors: updatedSensors
  });
});

// @route   PUT /api/sensors/:id
// @access  Private (admin)
const updateSensor = asyncHandler(async (req, res) => {
  const sensor = await Sensor.findOne({ id: req.params.id });

  if (!sensor) {
    res.status(404);
    throw new Error("Sensor not found");
  }

  Object.assign(sensor, req.body);

  await sensor.save();

  res.status(200).json({ success: true, sensor });
});


// @route   POST /api/sensors/:id/readings
// @access  Sensor bridge
const addSensorReadings = asyncHandler(async (req, res) => {
  const id = await getNextSequence("complaintId");
  const sensor = await Sensor.findOne({ id: req.params.id });

  if (!sensor) {
    res.status(404);
    throw new Error("Sensor not found");
  }

  const { readings } = req.body;

  if (
    !Array.isArray(readings) ||
    readings.length !== 3 ||
    readings.some((value) => typeof value !== "number")
  ) {
    res.status(400);
    throw new Error("readings must be an array of exactly 3 numbers");
  }

  const getUrgency = (value) => {
    if (value <= 40) return "Low";
    if (value <= 60) return "High";
    return "Critical";
  };

  const now = new Date();

  const recentReadings = readings.map((value, index) => ({
    time: new Date(now.getTime() + index * 1000).toLocaleTimeString(),
    value: `${value}%`,
    numericValue: value,
    urgency: getUrgency(value),
  }));

  const latestValue = readings[readings.length - 1];

  sensor.currentValue = latestValue;
  sensor.currentReading = `${latestValue}%`;
  sensor.urgency = getUrgency(latestValue);
  sensor.lastReadingTime = now.toLocaleString();

  sensor.lastReadingAt = now;
  sensor.status = "Online";
  sensor.recentReadings = recentReadings;


  // ==============================
  // CRITICAL WATER LEVEL DETECTION
  // ==============================
// If the sensor was disconnected for several seconds,
// treat the next reading as a new monitoring episode.
if (sensor.lastReadingAt) {
  const timeSinceLastReading =
    Date.now() - new Date(sensor.lastReadingAt).getTime();

  if (timeSinceLastReading >= 5000) {
    sensor.criticalSince = null;
    sensor.criticalComplaintCreated = false;
    sensor.belowThresholdSince = null;

    console.log(
      `🔄 ${sensor.id} started a new monitoring episode after reconnect.`
    );
  }
}
if (latestValue >= 80) {

  // Sensor is critical again
  sensor.belowThresholdSince = null;

  if (!sensor.criticalSince) {
    sensor.criticalSince = new Date();
  }

  const criticalDuration =
    Date.now() - new Date(sensor.criticalSince).getTime();

  if (
    criticalDuration >= 2000 &&
    !sensor.criticalComplaintCreated
  ) {

    const id = await getNextSequence("complaintId");

    const complaint = new Complaint({
      id,
      source: "Sensor",
      title: "Critical Water Level Detected",
      issue: "Water & Drainage",
      description:
        "Water level at XYZ Drain has crossed the critical threshold of 80% and remained above the threshold for more than 2 seconds. An automated complaint has been generated for official review.",
      category: "Water & Drainage",
      urgency: "Critical",
      status: "Pending Review",
      evidence: [],
      sensorEvidence: {
        sensorId: sensor.id,
        model: sensor.modelName,
        location: sensor.location,
        reading: `${latestValue}%`,
        threshold: "80%",
        status: "Critical"
      },
      history: [
        {
          status: "Pending Review",
          date: new Date().toLocaleDateString(),
          time: new Date().toLocaleTimeString(),
          notes:
            "Automatically generated by the water-level sensor after remaining above the critical threshold for more than 2 seconds."
        }
      ]
    });

    await complaint.save();

    sensor.criticalComplaintCreated = true;

    console.log(
      `🚨 Sensor complaint created for ${sensor.id} at ${latestValue}%`
    );
  }

} else {

  // Start recovery timer
  if (!sensor.belowThresholdSince) {
    sensor.belowThresholdSince = new Date();
  }

  const recoveryDuration =
    Date.now() - new Date(sensor.belowThresholdSince).getTime();

  // Require 5 seconds below threshold before
  // considering the critical episode finished.
  if (recoveryDuration >= 5000) {

    sensor.criticalSince = null;
    sensor.criticalComplaintCreated = false;
    sensor.belowThresholdSince = null;

    console.log(
      `✅ ${sensor.id} recovered below critical threshold.`
    );
  }
}


  await sensor.save();

  res.status(200).json({
    success: true,
    sensor,
  });
});


module.exports = {
  getSensors,
  updateSensor,
  addSensorReadings,
};